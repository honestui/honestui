import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const examplesDirectory = path.join(projectRoot, "registry/default/examples/shaders");
const outputPath = path.join(projectRoot, "registry/shader-index.tsx");

const files = (await readdir(examplesDirectory))
  .filter((file) => file.endsWith(".tsx"))
  .sort((a, b) => a.localeCompare(b));

const entries = await Promise.all(
  files.map(async (file, index) => {
    const name = file.slice(0, -4);
    const source = await readFile(path.join(examplesDirectory, file), "utf8");
    const namedExport = source.match(
      /\bexport\s+(?:async\s+)?(?:function|const|class)\s+([A-Za-z_$][\w$]*)/,
    )?.[1];

    if (!namedExport && !/\bexport\s+default\b/.test(source)) {
      throw new Error(`No component export found in ${file}`);
    }

    return {
      name,
      identifier: `shaderExample${index}`,
      namedExport,
    };
  }),
);

const imports = entries
  .map(({ name, identifier, namedExport }) =>
    namedExport
      ? `import { ${namedExport} as ${identifier} } from "./default/examples/shaders/${name}";`
      : `import ${identifier} from "./default/examples/shaders/${name}";`,
  )
  .join("\n");

const indexEntries = entries
  .map(({ name, identifier }) => `  ${JSON.stringify(name)}: { component: ${identifier} },`)
  .join("\n");

const output = `// This file is generated by \`npm run registry:shaders\`.\nimport type { ComponentType } from "react";\n\n${imports}\n\nexport const ShaderIndex: Record<string, { component: ComponentType }> = {\n${indexEntries}\n};\n`;

await writeFile(outputPath, output);
console.log(`Indexed ${entries.length} shader examples.`);

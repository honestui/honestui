const NEW_WINDOW_MS = 14 * 24 * 60 * 60 * 1000;

const NEW_PAGE_DATES = new Map(NEW_PAGES.map((page) => [page.url, page.releasedOn]));

export function isRecentlyReleased(url: string): boolean {
  let releasedOn = NEW_PAGE_DATES.get(url);
  // A chart folder's pages live one level down, such as /docs/charts/tracker/static.
  if (!releasedOn) {
    const parent = url.slice(0, url.lastIndexOf("/"));
    if (parent.startsWith("/docs/charts/") && !parent.startsWith("/docs/charts/honesty")) {
      releasedOn = NEW_PAGE_DATES.get(parent);
    }
  }
  if (!releasedOn) {
    return false;
  }
  return Date.now() - Date.parse(releasedOn) < NEW_WINDOW_MS;
}
